def short_form(p, rng):
    """三种短说法：正式 / 口语 / 细节。均 40-120 字，表达同一事实。"""
    (name, kind, dim, chosen, alt, reason, note,
     dim2, chosen2, alt2, reason2) = p
    s1 = f"{name}这个{kind}，{dim}最后定的是{chosen}。当时没选{alt}，因为{reason}。有一条要记住：{note}。"
    s2 = (f"对了，{name}那边{dim}走的是{chosen}，本来想过{alt}，"
          f"后来发现{reason}，就换掉了。{note}这点别忘了。")
    s3 = (f"补充一下{name}（{kind}）的背景：{dim}这块一开始的方案其实是{alt}，"
          f"评估下来{reason}，所以最终采用{chosen}。另外{note}，这个是踩过坑之后加的约束。")
    return [s1, s2, s3]


def long_form(p, rng):
    """长说法：200-300 字，把背景、取舍、结论都铺开，用于验证"拉长语义单元"假设。"""
    (name, kind, dim, chosen, alt, reason, note,
     dim2, chosen2, alt2, reason2) = p
    users = rng.choice(["内部运营团队", "几条业务线的分析师", "客服中心", "外部客户的门户", "一线的运维同事"])
    team = rng.choice(["三个人", "五个人", "两个后端加一个前端", "六个人的小组"])
    duty = rng.choice(["后端和整体架构", "数据链路这部分", "部署和运维", "前端的交互"])
    trouble = rng.choice(["中间换过一次负责人", "需求改了三四轮", "差点因为预算被砍掉", "上线前压测出过一次事故"])
    alt_good = rng.choice(["上手快、生态成熟", "社区资料多、出问题好查", "前期投入小", "和现有技术栈更接近"])
    cost = rng.choice(["需要额外维护一套集群", "团队得重新学", "初期接入要多花两周", "运维复杂度会上一个台阶"])
    gain = rng.choice(["长期看更省心", "扩展性明显更好", "故障面小很多", "和后续规划能对上"])
    later = rng.choice(["下一阶段准备把监控补齐", "后面还要做一次容量评估", "明年可能要考虑多机房", "暂时先这样跑着"])

    variants = [
        (f"{name}是去年立项的一个{kind}，主要给{users}用，团队{team}，我负责{duty}。"
         f"{trouble}。到{dim}这一步，我们认真比较过{alt}和{chosen}两种做法："
         f"{alt}的好处是{alt_good}，但{reason}；{chosen}的代价是{cost}，不过{gain}。"
         f"所以最后拍板定的是{chosen}。有一条必须记住：{note}。后续{later}。"),
        (f"说一下{name}这个项目吧，{kind}，是给{users}做的，我们{team}在弄，我主要管{duty}，"
         f"中间{trouble}。{dim}当时纠结了很久，{alt}其实也能用，毕竟{alt_good}，"
         f"但问题在于{reason}。换成{chosen}以后，虽然{cost}，可{gain}。"
         f"结论就是{chosen}。另外{note}，这个坑我们踩过一次。后面{later}。"),
        (f"{name}（{kind}，去年立项，服务{users}，团队{team}，我负责{duty}，期间{trouble}）"
         f"在{dim}上的最终结论是{chosen}。评估过程简述：候选方案为{alt}与{chosen}，"
         f"{alt}的优势是{alt_good}，但{reason}，这一条足以否掉它；"
         f"{chosen}需要接受{cost}，换来的是{gain}。因此采用{chosen}。"
         f"约束条件：{note}。后续计划：{later}。"),
    ]
    return variants


def build():
    rng = random.Random(SEED)
    groups = {}

    # ---- G1 跨域（等长版）：每个领域 3 条，共 30 条，长度对齐 G2
    g1 = []
    for i, (dom, s1, s2, s3) in enumerate(CROSS_DOMAIN, 1):
        tmpl = DOMAIN_LONG[dom]
        texts = [t.format(fact=f) for t, f in zip(tmpl, (s1, s2, s3))]
        g1.append({"id": f"G1-{i:02d}", "tag": dom, "texts": texts})
    groups["G1_cross_same_len"] = g1

    # ---- G2 同域短：30 个项目，取第一个维度
    g2 = []
    for i, p in enumerate(PROJECTS, 1):
        g2.append({"id": f"G2-{i:02d}", "tag": p[0], "texts": short_form(p, rng)})
    groups["G2_same_short"] = g2

    # ---- G3 同域长：同样 30 个项目，长说法
    g3 = []
    for i, p in enumerate(PROJECTS, 1):
        g3.append({"id": f"G3-{i:02d}", "tag": p[0], "texts": long_form(p, rng)})
    groups["G3_same_long"] = g3

    # ---- G4 同项目双维度：60 条，同项目名只差维度
    # ---- G5 信息量递减：同 G4，但查询侧逐级剥掉信息（完整 → 只留结论 → 只留项目名）
    g4, g5 = [], []
    for i, p in enumerate(PROJECTS, 1):
        name, kind = p[0], p[1]
        a = (name, kind, p[2], p[3], p[4], p[5], p[6], p[7], p[8], p[9], p[10])
        b = (name, kind, p[7], p[8], p[9], p[10], p[6], p[2], p[3], p[4], p[5])
        ta, tb = short_form(a, rng), short_form(b, rng)
        g4.append({"id": f"G4-{i:02d}a", "tag": f"{name}/{p[2]}", "texts": ta})
        g4.append({"id": f"G4-{i:02d}b", "tag": f"{name}/{p[7]}", "texts": tb})
        for suffix, dim, chosen, full in (("a", p[2], p[3], ta[0]), ("b", p[7], p[8], tb[0])):
            g5.append({
                "id": f"G5-{i:02d}{suffix}",
                "tag": f"{name}/{dim}",
                "texts": [
                    full,                                        # 变体0：完整（建库用）
                    f"{name}项目的{dim}最后定的是{chosen}。",       # 变体1：只留结论
                    f"{name}那边的事就按之前定的来。",               # 变体2：只剩项目名
                ],
            })
    groups["G4_same_project"] = g4
    groups["G5_info_decay"] = g5

    return {
        "seed": SEED,
        "note": "每条 3 种说法对应同一事实（s1 正式 / s2 口语 / s3 细节），"
                "用于测「类内可变性」；不同条目之间测「类间可区分性」",
        "groups": groups,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="data/p0_corpus.json")
    args = ap.parse_args()

    data = build()
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)

    print(f"written: {args.out}")
    for g, items in data["groups"].items():
        lens = [len(t) for it in items for t in it["texts"]]
        print(f"  {g:20s} items={len(items):3d} texts={len(items)*3:3d} "
              f"len min/mean/max = {min(lens)}/{sum(lens)//len(lens)}/{max(lens)}")


if __name__ == "__main__":
    main()
